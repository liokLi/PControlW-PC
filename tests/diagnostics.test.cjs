const { test } = require('node:test')
const assert = require('node:assert/strict')
const { createDiagnostics } = require('../electron/diagnostics.cjs')

test('matches sending and reception intervals despite different clock origins', () => {
  const stats = createDiagnostics()
  stats.receive({ gesture: 1, seq: 1, sentAt: 100000 }, 10)
  stats.execute(11)
  stats.receive({ gesture: 1, seq: 2, sentAt: 100017 }, 210)
  stats.execute(211)
  stats.loop(170)
  const result = stats.snapshot()
  assert.equal(result.sent.maxGap, 17)
  assert.equal(result.received.maxGap, 200)
  assert.equal(result.transitGrowthMax, 183)
  assert.equal(result.executed.maxGap, 200)
  assert.equal(result.received.longGaps, 1)
  assert.equal(result.sequenceErrors, 0)
  assert.equal(result.loopMax, 170)
  assert.deepEqual(result.stalls, [{ seq: 2, sendGap: 17, receiveGap: 200 }])
})

test('retains bounded stall records and separates deliberate sender gaps from added delay', () => {
  const stats = createDiagnostics()
  for (let i = 1; i <= 9; i++) stats.receive({ gesture: 2, seq: i, sentAt: i * 100 }, i * 100 + 1000)
  let result = stats.snapshot()
  assert.equal(result.transitGrowthMax, 0)
  assert.equal(result.sent.longGaps, 8)
  assert.equal(result.stalls.length, 5)
  stats.receive({ gesture: 2, seq: 11, sentAt: 1000 }, 2000)
  assert.equal(stats.snapshot().sequenceErrors, 1)
  stats.reset()
  stats.receive(undefined, 10000)
  result = stats.snapshot()
  assert.equal(result.received.count, 1)
  assert.equal(result.received.maxGap, 0)
  assert.equal(result.sent.count, 0)
  assert.equal(result.gesture, null)
  assert.equal(result.stalls.length, 0)
})
